function passage(title, genre, emoji, text, questions, grade = 'ป.5') {
  const mainQ = questions[0];
  return {
    word: title,
    reading: genre,
    meaning: mainQ.explain || `อ่านแล้วตอบ: ${mainQ.q}`,
    emoji,
    grade,
    indicator_code: IND,
    item_type: 'reading',
    pos: genre,
    pos_label: genre,
    passage: text,
    questions,
    sentence: text.slice(0, 60) + '…',
    highlight: title,
  };
}

