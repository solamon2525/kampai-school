function mkConsonant([char, name, reading, emoji, examples], cls) {
  const labels = { high: 'พยัญชนะสูง', mid: 'พยัญชนะกลาง', low: 'พยัญชนะต่ำ' };
  return {
    word: char,
    reading,
    meaning: `${labels[cls]} · ${name} · ตัวอย่าง: ${examples.join(', ')}`,
    emoji,
    grade: 'ป.1',
    indicator_code: 'ท 4.1 ป.1/1',
    char_class: cls,
    item_type: 'consonant',
    name,
    examples,
  };
}

