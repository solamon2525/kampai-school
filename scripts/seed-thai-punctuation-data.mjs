function mk(mark, label, gloss, emoji, blank, full, grade = 'ป.4') {
  const slug = mark.replace(/[^\p{L}\p{N}]/gu, '') || 'mark';
  return {
    word: `${label} ( ${mark} )`,
    reading: label,
    meaning: `${gloss} · ตัวอย่าง: ${full}`,
    emoji,
    grade,
    indicator_code: IND,
    item_type: 'punctuation',
    pos: slug,
    pos_label: mark,
    mark,
    sentence: blank,
    sentence_answer: full,
    highlight: mark,
  };
}

