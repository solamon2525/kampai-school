const allItems = [...noun, ...verb, ...adjective, ...adverb, ...preposition, ...conjunction, ...interjection, ...demonstrative];

function pickMixed(n) {
  const shuffled = [...allItems].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, n).map((item) => ({
    ...item,
    meaning: `[ทบทวน] ${item.meaning}`,
  }));
}

const itemMap = {
  noun,
  verb,
  adjective,
  adverb,
  preposition,
  conjunction,
  interjection,
  demonstrative,
  'mixed-drill': pickMixed(24),
};

writeFileSync(join(DATA, 'categories.json'), `${JSON.stringify(categories, null, 2)}\n`, 'utf8');

for (const cat of categories) {
  const items = itemMap[cat.slug];
  writeFileSync(join(ITEMS, `${cat.slug}.json`), `${JSON.stringify(items, null, 2)}\n`, 'utf8');
}

const total = Object.values(itemMap).reduce((s, a) => s + a.length, 0);
console.log(`✅ Seeded ${total} grammar items in ${categories.length} categories → ${HUB}/data/`);
