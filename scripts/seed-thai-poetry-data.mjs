function poem(title, genre, emoji, passage, meaning, extra = {}) {
  return {
    word: title,
    reading: genre,
    meaning,
    emoji,
    grade: extra.grade || 'ป.4',
    indicator_code: extra.indicator || IND,
    item_type: 'poetry',
    pos: genre,
    pos_label: genre,
    passage,
    sentence: passage.split('\n')[0],
    highlight: title,
    rhyme_hint: extra.rhyme_hint || '',
    questions: extra.questions || [],
  };
}

