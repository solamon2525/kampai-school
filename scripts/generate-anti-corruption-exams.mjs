// Balance answer distribution across 0, 1, 2, 3 deterministically
// So that correct answers are evenly spread across choices ก, ข, ค, ง
questions.forEach((q, idx) => {
  const desiredAnswer = idx % 4; // 0, 1, 2, 3 evenly distributed
  if (q.answer !== desiredAnswer) {
    const correctOpt = q.options[q.answer];
    const targetOpt = q.options[desiredAnswer];
    q.options[desiredAnswer] = correctOpt;
    q.options[q.answer] = targetOpt;
    q.answer = desiredAnswer;
  }
});

console.log(`Total questions defined: ${questions.length}`);

// Validate questions:
// 1. Exactly 150 questions
if (questions.length !== 150) {
  throw new Error(`Expected 150 questions, got ${questions.length}`);
}

// 2. Counts per difficulty
const diffCounts = { easy: 0, medium: 0, hard: 0 };
questions.forEach(q => diffCounts[q.difficulty]++);
console.log('Difficulty breakdown:', diffCounts);

// 3. Counts per answer choice
const answerCounts = { 0: 0, 1: 0, 2: 0, 3: 0 };
questions.forEach(q => answerCounts[q.answer]++);
console.log('Answer key distribution:', answerCounts);

// 4. Duplicate checks
const textSet = new Set();
for (let i = 0; i < questions.length; i++) {
  const q = questions[i];
  if (textSet.has(q.text)) {
    throw new Error(`Duplicate question found at index ${i}: "${q.text}"`);
  }
  textSet.add(q.text);

  if (!q.options || q.options.length !== 4) {
    throw new Error(`Question ${i} does not have 4 options: "${q.text}"`);
  }
  if (q.answer < 0 || q.answer > 3) {
    throw new Error(`Question ${i} invalid answer index ${q.answer}`);
  }
  if (!q.explanation || q.explanation.trim().length === 0) {
    throw new Error(`Question ${i} missing explanation`);
  }
}

