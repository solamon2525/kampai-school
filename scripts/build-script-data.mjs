#!/usr/bin/env node
/**
 * รวม data/categories.json + data/items/*.json → thai-script-hub/data.js
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const HUB = join(ROOT, 'public/games/thai/thai-script-hub');
const DATA_DIR = join(HUB, 'data');
const ITEMS_DIR = join(DATA_DIR, 'items');
const OUT_FILE = join(HUB, 'data.js');

function loadJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

const categories = loadJson(join(DATA_DIR, 'categories.json'));
const words = {};
for (const cat of categories) {
  const f = join(ITEMS_DIR, `${cat.slug}.json`);
  if (!existsSync(f)) {
    console.error('❌ Missing', f);
    process.exit(1);
  }
  words[cat.slug] = loadJson(f);
}

const header = `/* data.js — AUTO-GENERATED by scripts/build-script-data.mjs — DO NOT EDIT BY HAND */
/* แก้ที่ data/categories.json + data/items/<slug>.json แล้วรัน: node scripts/build-script-data.mjs */
`;
writeFileSync(OUT_FILE, header + `window.GAME_DATA = ${JSON.stringify({ categories, words }, null, 2)};\n`, 'utf8');

const total = Object.values(words).reduce((s, a) => s + a.length, 0);
console.log(`✅ Built data.js — ${total} items / ${categories.length} categories`);
