/**
 * Validates an enriched word item according to Thai Vocab Hub standards
 */
export function validateEnrichedItem(item) {
  const errors = [];
  if (!item || typeof item !== 'object') {
    return { isValid: false, errors: ['Item must be an object'] };
  }

  if (!item.word || typeof item.word !== 'string') errors.push('Missing word');
  if (!item.reading || typeof item.reading !== 'string') errors.push('Missing reading');
  if (!item.meaning || typeof item.meaning !== 'string') errors.push('Missing meaning');
  if (!item.pos || typeof item.pos !== 'string') errors.push('Missing pos');
  if (!item.grade || typeof item.grade !== 'string') errors.push('Missing grade');
  if (!item.indicator_code || typeof item.indicator_code !== 'string') errors.push('Missing indicator_code');
  if (!item.emoji || typeof item.emoji !== 'string') errors.push('Missing emoji');

  if (!item.example || typeof item.example !== 'string') {
    errors.push('Missing example');
  } else {
    for (const pat of PLACEHOLDER_PATTERNS) {
      if (item.example.includes(pat)) {
        errors.push(`Example contains placeholder pattern: "${pat}"`);
      }
    }
    if (!item.example.includes(item.word)) {
      errors.push(`Example does not contain the word "${item.word}"`);
    }
  }

  return {
    isValid: errors.length === 0,
    errors
  };
}

