import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage();
 const runtimeErrors=[];
 page.on('pageerror',error=>runtimeErrors.push(error.message));
 page.on('console',message=>{const location=message.location();const blockedGoogleFont=message.text().includes('ERR_NETWORK_ACCESS_DENIED')&&location.url.startsWith('https://fonts.googleapis.com/');if(message.type()==='error'&&!blockedGoogleFont)runtimeErrors.push(message.text())});
 await page.addInitScript(()=>{
  window.testSpeech=[];
  window.SpeechSynthesisUtterance=class{constructor(text){this.text=text}};
  Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>[{lang:'en-US',name:'Test'}],cancel(){},speak(u){window.testSpeech.push(u);u.onstart?.()}}});
 });
 await page.goto('http://127.0.0.1:8080/games/english/everyday-conversation-p4-media.html');
 assert.equal(await page.evaluate(()=>testSpeech.length),0);
 await page.locator('[data-mode="myself"]').click();
 await page.locator('#profileName').fill('Nina');
 await page.locator('#profileSchool').fill('TEST SCHOOL');
 await page.locator('#schoolSpeech').fill('Test School');
 await page.locator('#btnUseProfile').click();
 assert.match(await page.locator('#dialogue').innerText(),/Mali/);
 await page.locator('#btnUseProfile').click();
 assert.match(await page.locator('#dialogue').innerText(),/Nina/);
 await page.locator('[data-mode="learn"]').click();
 assert.match(await page.locator('#dialogue').innerText(),/Hi, Nina/);
 assert.equal(await page.evaluate(()=>testSpeech.length),0);
 await page.locator('#btnListen').click();
 assert.equal(await page.evaluate(()=>testSpeech.at(-1).text),'Hello! My name is Nina.');
 await page.evaluate(()=>testSpeech.at(-1).onboundary({charIndex:7,name:'word'}));
 assert.equal(await page.locator('#dialogue .spoken-word').innerText(),'My');
 assert.equal(await page.locator('#visualEnglish .spoken-word').innerText(),'My');
 assert.deepEqual(await page.evaluate(()=>{const state=EverydayConversationP4.getState();return [state.karaokeWordIndex,state.karaokeSync]}),[1,'boundary']);
 assert.equal(await page.locator('#dialogue .line.active').evaluate(el=>el.classList.contains('speaking')),true);
 assert.equal(await page.locator('#visualSpeech').evaluate(el=>el.classList.contains('speaking')),true);
 const karaokeContrast=await page.locator('#dialogue .spoken-word').evaluate(el=>{const style=getComputedStyle(el);return {color:style.color,background:style.backgroundColor,weight:Number(style.fontWeight)}});
 assert.notEqual(karaokeContrast.color,karaokeContrast.background);
 assert.ok(karaokeContrast.weight>=800);
 await page.locator('#btnNext').click();
 await page.evaluate(()=>testSpeech.at(-1).onboundary({charIndex:7,name:'word'}));
 assert.equal(await page.locator('.spoken-word').count(),0);
 assert.deepEqual(await page.evaluate(()=>{const state=EverydayConversationP4.getState();return [state.karaokeWordIndex,state.karaokeSync]}),[-1,'idle']);
 await page.locator('[data-mode="visual"]').click();
 await page.locator('#btnListen').click();
 await page.evaluate(()=>testSpeech.at(-1).onboundary({charIndex:0,name:'word'}));
 assert.equal(await page.locator('#visualEnglish .spoken-word').innerText(),'Hello!');
 assert.equal(await page.locator('#dialogue .spoken-word').innerText(),'Hello!');
 await page.locator('#btnNext').click();
 await page.locator('#btnListen').click();
 await page.waitForTimeout(260);
 assert.deepEqual(await page.evaluate(()=>{const state=EverydayConversationP4.getState();return [state.karaokeWordIndex,state.karaokeSync]}),[0,'fallback']);
 assert.equal(await page.locator('#visualEnglish .spoken-word').count(),1);
 await page.locator('#btnNext').click();
 assert.equal(await page.locator('.spoken-word').count(),0);
 await page.locator('[data-mode="practice"]').click();
 await page.locator('#practiceRole').selectOption('A');
 const before=await page.evaluate(()=>testSpeech.length);
 await page.locator('#btnPlay').click();
 assert.equal(await page.locator('#continueRole').isVisible(),true);
 assert.equal(await page.evaluate(()=>testSpeech.length),before);
 await page.locator('#continueRole').click();
 assert.match(await page.evaluate(()=>testSpeech.at(-1).text),/^Hi, Nina/);
 await page.locator('[data-mode="myself"]').click();
 await page.locator('#profileName').focus();
 const line=await page.evaluate(()=>EverydayConversationP4.getState().line);
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.evaluate(()=>EverydayConversationP4.getState().line),line);
 const saved=await page.evaluate(()=>localStorage.getItem('conversation_p4_teacher'));
 assert.deepEqual(Object.keys(JSON.parse(saved)).sort(),['province','school','schoolSpeech']);
 await page.locator('[data-mode="learn"]').click();
 await page.locator('#toggleReading').click();
 assert.equal(await page.locator('#dialogue .reading').first().evaluate(el=>getComputedStyle(el).display),'none');
 assert.equal(await page.locator('#visualReading').evaluate(el=>getComputedStyle(el).display),'none');
 await page.locator('#toggleReading').click();
 await page.locator('#toggleMeaning').click();
 assert.equal(await page.locator('#dialogue .meaning').first().evaluate(el=>getComputedStyle(el).display),'none');
 assert.equal(await page.locator('#visualMeaning').evaluate(el=>getComputedStyle(el).display),'none');
 await page.locator('#toggleMeaning').click();
 for(const [width,height] of [[360,800],[768,1024],[1280,720]]){
  await page.setViewportSize({width,height});
  for(const mode of ['learn','visual']){
   await page.locator(`[data-mode="${mode}"]`).click();
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${mode} overflow at ${width}`);
   const readingSelector=mode==='visual'?'#visualReading':'#dialogue .line.active .reading';
   const meaningSelector=mode==='visual'?'#visualMeaning':'#dialogue .line.active .meaning';
   const readingMin=width<=767?24:mode==='visual'?28:30;
   const meaningMin=width<=767?20:mode==='visual'?24:26;
   assert.ok(await page.locator(readingSelector).evaluate((el,min)=>parseFloat(getComputedStyle(el).fontSize)>=min,readingMin),`${mode} reading too small at ${width}`);
   assert.ok(await page.locator(meaningSelector).evaluate((el,min)=>parseFloat(getComputedStyle(el).fontSize)>=min,meaningMin),`${mode} meaning too small at ${width}`);
  }
 }
 assert.deepEqual(runtimeErrors,[]);
 console.log('PASS: silent entry, profile toggle, linked names, synchronized karaoke boundary/fallback, cancellation, A/B wait, input arrows, teacher-only persistence, responsive reading and meaning sizes');
}finally{await browser.close()}
