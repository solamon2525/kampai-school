#!/usr/bin/env node
/**
 * รวม data/categories.json + data/words/*.json → public/games/thai/thai-vocab-hub/data.js
 * Usage: node scripts/build-vocab-data.mjs [--check]
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const HUB = join(ROOT, 'public/games/thai/thai-vocab-hub');
const DATA_DIR = join(HUB, 'data');
const CATEGORIES_FILE = join(DATA_DIR, 'categories.json');
const WORDS_DIR = join(DATA_DIR, 'words');
const OUT_FILE = join(HUB, 'data.js');
const TARGET_PER_CATEGORY = 200;

const checkOnly = process.argv.includes('--check');

function loadJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function build() {
  if (!existsSync(CATEGORIES_FILE)) {
    console.error('❌ Missing', CATEGORIES_FILE);
    process.exit(1);
  }

  const categories = loadJson(CATEGORIES_FILE);
  const words = {};
  const slugs = new Set(categories.map((c) => c.slug));

  for (const slug of slugs) {
    const wordFile = join(WORDS_DIR, `${slug}.json`);
    if (!existsSync(wordFile)) {
      console.error(`❌ Missing word file: data/words/${slug}.json`);
      process.exit(1);
    }
    words[slug] = loadJson(wordFile);
  }

  // orphan word files
  if (existsSync(WORDS_DIR)) {
    for (const f of readdirSync(WORDS_DIR).filter((x) => x.endsWith('.json'))) {
      const slug = f.replace(/\.json$/, '');
      if (!slugs.has(slug)) {
        console.warn(`⚠️  Orphan word file (no category): ${f}`);
      }
    }
  }

  let total = 0;
  const counts = [];
  for (const cat of categories) {
    const n = (words[cat.slug] || []).length;
    total += n;
    counts.push({ slug: cat.slug, title: cat.title, count: n });
  }

  const header = `/* data.js — AUTO-GENERATED by scripts/build-vocab-data.mjs — DO NOT EDIT BY HAND */
/* แก้ที่ data/categories.json และ data/words/<slug>.json แล้วรัน: pnpm build:vocab */
`;

  const body = `window.GAME_DATA = ${JSON.stringify({ categories, words }, null, 2)};\n`;
  const out = header + body;

  if (checkOnly) {
    let ok = true;
    for (const { slug, title, count } of counts) {
      if (count !== TARGET_PER_CATEGORY) {
        console.error(`❌ ${title} (${slug}): ${count}/${TARGET_PER_CATEGORY} คำ`);
        ok = false;
      } else {
        console.log(`✅ ${title}: ${count} คำ`);
      }
    }
    console.log(`\nรวม ${total} คำ / ${categories.length} หมวด`);
    process.exit(ok ? 0 : 1);
  }

  writeFileSync(OUT_FILE, out, 'utf8');
  console.log(`✅ Wrote ${OUT_FILE}`);
  console.log(`   ${categories.length} หมวด · ${total} คำ`);
  for (const { title, count } of counts) {
    const mark = count === TARGET_PER_CATEGORY ? '✓' : '⚠';
    console.log(`   ${mark} ${title}: ${count}`);
  }
}

build();
