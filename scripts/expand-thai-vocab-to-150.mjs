function loadItems(slug) {
  return JSON.parse(readFileSync(join(WORDS_DIR, `${slug}.json`), 'utf8'));
}

function saveItems(slug, items) {
  writeFileSync(join(WORDS_DIR, `${slug}.json`), JSON.stringify(items, null, 2) + '\n', 'utf8');
}

for (const [slug, candidates] of Object.entries(packs)) {
  const items = loadItems(slug);
  const seen = new Set(items.map((item) => item.word));
  const additions = [];

  for (const candidate of candidates) {
    if (items.length + additions.length >= TARGET_PER_CATEGORY) break;
    if (!candidate.word || seen.has(candidate.word)) continue;
    const entry = {
      ...candidate,
      indicator_code: candidate.indicator_code || INDICATORS[slug],
      difficulty: candidate.difficulty || difficultyByGrade[candidate.grade] || null,
    };
    additions.push(entry);
    seen.add(entry.word);
  }

  if (items.length + additions.length !== TARGET_PER_CATEGORY) {
    throw new Error(`${slug}: expected ${TARGET_PER_CATEGORY}, got ${items.length + additions.length}. Need ${TARGET_PER_CATEGORY - items.length - additions.length} more candidates.`);
  }

  if (additions.length > 0) {
    saveItems(slug, [...items, ...additions]);
  }
  console.log(`✅ ${slug}: ${items.length} + ${additions.length} = ${items.length + additions.length}`);
}
