function esc(str) {
  if (str === null || str === undefined) return 'NULL';
  return "'" + String(str).replace(/'/g, "''") + "'";
}

function sqlJsonb(obj) {
  return `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;
}

function sqlJsonbText(val) {
  return `to_jsonb(${esc(val)}::text)`;
}

const questions = [];

function addQ(subject, topic, text, modelAnswer, criteria, keywords, exp, indCode, indDesc, mId, mTitle, mImg) {
  questions.push({
    subject,
    grade: 'ป.4',
    topic,
    difficulty: 'easy',
    bloom_level: 'L2',
    question_type: 'essay',
    question_text: text,
    answer: modelAnswer,
    rubric: {
      full_score: 5,
      key_solution: modelAnswer.split('\n')[0],
      criteria,
      keywords
    },
    explanation: exp,
    indicator_code: indCode,
    indicator_desc: indDesc,
    media_item_id: mId,
    media_title: mTitle,
    media_image_url: mImg
  });
}

