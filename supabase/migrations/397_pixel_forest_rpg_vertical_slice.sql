CREATE OR REPLACE FUNCTION public.get_pixel_forest_rpg_state(p_student_code text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_student_id uuid;
  v_profile public.pixel_forest_rpg_profiles%ROWTYPE;
BEGIN
  SELECT s.id INTO v_student_id
  FROM public.students s
  WHERE s.student_code = btrim(p_student_code)
    AND s.is_active IS NOT FALSE
  LIMIT 1;

  IF v_student_id IS NULL THEN
    RAISE EXCEPTION 'RPG_STUDENT_NOT_FOUND';
  END IF;

  INSERT INTO public.pixel_forest_rpg_profiles (student_id)
  VALUES (v_student_id)
  ON CONFLICT (student_id) DO NOTHING;

  SELECT * INTO v_profile
  FROM public.pixel_forest_rpg_profiles
  WHERE student_id = v_student_id;

  RETURN jsonb_build_object(
    'state_version', v_profile.state_version,
    'save_state', v_profile.save_state,
    'saved_at', v_profile.updated_at
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.save_pixel_forest_rpg_state(
  p_student_code text,
  p_expected_version int,
  p_idempotency_key text,
  p_state jsonb,
  p_events jsonb DEFAULT '[]'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_student_id uuid;
  v_profile public.pixel_forest_rpg_profiles%ROWTYPE;
  v_class text;
  v_level int;
  v_xp int;
  v_gold int;
  v_gems int;
  v_chapter int;
  v_zone text;
  v_gold_delta int;
  v_gem_delta int;
  v_event jsonb;
  v_new_version int;
BEGIN
  IF p_idempotency_key IS NULL OR char_length(p_idempotency_key) NOT BETWEEN 8 AND 80
     OR p_idempotency_key !~ '^[a-zA-Z0-9:_-]+$' THEN
    RAISE EXCEPTION 'RPG_INVALID_SAVE_KEY';
  END IF;
  IF p_state IS NULL OR jsonb_typeof(p_state) <> 'object'
     OR octet_length(p_state::text) > 100000 THEN
    RAISE EXCEPTION 'RPG_INVALID_STATE';
  END IF;
  IF p_events IS NULL OR jsonb_typeof(p_events) <> 'array'
     OR jsonb_array_length(p_events) > 30 THEN
    RAISE EXCEPTION 'RPG_INVALID_EVENTS';
  END IF;

  SELECT s.id INTO v_student_id
  FROM public.students s
  WHERE s.student_code = btrim(p_student_code)
    AND s.is_active IS NOT FALSE
  LIMIT 1;
  IF v_student_id IS NULL THEN RAISE EXCEPTION 'RPG_STUDENT_NOT_FOUND'; END IF;

  INSERT INTO public.pixel_forest_rpg_profiles (student_id)
  VALUES (v_student_id)
  ON CONFLICT (student_id) DO NOTHING;

  SELECT * INTO v_profile
  FROM public.pixel_forest_rpg_profiles
  WHERE student_id = v_student_id
  FOR UPDATE;

  IF v_profile.last_save_key = p_idempotency_key THEN
    RETURN jsonb_build_object('state_version', v_profile.state_version, 'save_state', v_profile.save_state, 'saved_at', v_profile.updated_at, 'replayed', true);
  END IF;
  IF p_expected_version IS DISTINCT FROM v_profile.state_version THEN
    RAISE EXCEPTION 'RPG_SAVE_CONFLICT:%', v_profile.state_version;
  END IF;

  v_class := NULLIF(p_state->>'hero_class', '');
  v_level := COALESCE((p_state->>'hero_level')::int, 1);
  v_xp := COALESCE((p_state->>'hero_xp')::int, 0);
  v_gold := COALESCE((p_state->>'gold')::int, 0);
  v_gems := COALESCE((p_state->>'gems')::int, 0);
  v_chapter := COALESCE((p_state->>'chapter')::int, 1);
  v_zone := COALESCE(NULLIF(p_state->>'zone', ''), 'village');

  IF v_class NOT IN ('swordsman', 'ranger', 'mage')
     OR v_level NOT BETWEEN 1 AND 50
     OR v_xp NOT BETWEEN 0 AND 10000000
     OR v_gold NOT BETWEEN 0 AND 10000000
     OR v_gems NOT BETWEEN 0 AND 1000000
     OR v_chapter NOT BETWEEN 1 AND 4
     OR v_zone NOT IN ('village', 'mosswood', 'swamp', 'ruins') THEN
    RAISE EXCEPTION 'RPG_STATE_OUT_OF_RANGE';
  END IF;
  IF jsonb_typeof(p_state->'inventory') <> 'object'
     OR jsonb_typeof(p_state->'equipment') <> 'object'
     OR jsonb_typeof(p_state->'unlocked_zones') <> 'array' THEN
    RAISE EXCEPTION 'RPG_STATE_SHAPE_INVALID';
  END IF;

  v_gold_delta := v_gold - v_profile.gold;
  v_gem_delta := v_gems - v_profile.gems;
  IF abs(v_gold_delta) > 10000 OR abs(v_gem_delta) > 1000 THEN
    RAISE EXCEPTION 'RPG_ECONOMY_DELTA_TOO_LARGE';
  END IF;

  v_new_version := v_profile.state_version + 1;
  UPDATE public.pixel_forest_rpg_profiles SET
    hero_class = v_class,
    hero_level = v_level,
    hero_xp = v_xp,
    gold = v_gold,
    gems = v_gems,
    current_chapter = v_chapter,
    current_zone = v_zone,
    save_state = p_state,
    state_version = v_new_version,
    last_save_key = p_idempotency_key,
    last_played_at = now(),
    updated_at = now()
  WHERE student_id = v_student_id;

  IF v_gold_delta <> 0 THEN
    INSERT INTO public.pixel_forest_economy_ledger
      (student_id, currency, amount, balance_after, reason, idempotency_key, metadata)
    VALUES
      (v_student_id, 'gold', v_gold_delta, v_gold, 'save_sync', p_idempotency_key, jsonb_build_object('chapter', v_chapter, 'zone', v_zone))
    ON CONFLICT DO NOTHING;
  END IF;
  IF v_gem_delta <> 0 THEN
    INSERT INTO public.pixel_forest_economy_ledger
      (student_id, currency, amount, balance_after, reason, idempotency_key, metadata)
    VALUES
      (v_student_id, 'gems', v_gem_delta, v_gems, 'save_sync', p_idempotency_key, jsonb_build_object('chapter', v_chapter, 'zone', v_zone))
    ON CONFLICT DO NOTHING;
  END IF;

  FOR v_event IN SELECT value FROM jsonb_array_elements(p_events)
  LOOP
    IF v_event->>'type' IN (
      'session_start', 'session_end', 'class_selected', 'zone_enter', 'monster_kill',
      'player_death', 'boss_start', 'boss_clear', 'chapter_complete', 'item_craft',
      'weapon_enhance', 'rune_equip', 'damage_dealt', 'damage_taken'
    ) THEN
      INSERT INTO public.pixel_forest_balance_events
        (student_id, event_type, hero_class, hero_level, chapter, zone, value, metadata)
      VALUES
        (v_student_id, v_event->>'type', v_class, v_level, v_chapter, v_zone,
         CASE WHEN (v_event->>'value') ~ '^-?[0-9]+([.][0-9]+)?$' THEN (v_event->>'value')::numeric ELSE NULL END,
         COALESCE(v_event->'metadata', '{}'::jsonb));
    END IF;
  END LOOP;

  RETURN jsonb_build_object('state_version', v_new_version, 'save_state', p_state, 'saved_at', now(), 'replayed', false);
END;
$function$;

REVOKE ALL ON FUNCTION public.get_pixel_forest_rpg_state(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.save_pixel_forest_rpg_state(text, int, text, jsonb, jsonb) FROM PUBLIC, anon, authenticated;
