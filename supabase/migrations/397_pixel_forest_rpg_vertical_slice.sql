-- Persistent RPG profile/economy/telemetry for pixel-forest-explorer v3.0.0.
-- Student identity follows the existing game boundary: a valid active student_code.

CREATE TABLE IF NOT EXISTS public.pixel_forest_rpg_profiles (
  student_id       uuid PRIMARY KEY REFERENCES public.students(id) ON DELETE CASCADE,
  hero_class       text CHECK (hero_class IS NULL OR hero_class IN ('swordsman', 'ranger', 'mage')),
  hero_level       int NOT NULL DEFAULT 1 CHECK (hero_level BETWEEN 1 AND 50),
  hero_xp          int NOT NULL DEFAULT 0 CHECK (hero_xp BETWEEN 0 AND 10000000),
  gold             int NOT NULL DEFAULT 150 CHECK (gold BETWEEN 0 AND 10000000),
  gems             int NOT NULL DEFAULT 0 CHECK (gems BETWEEN 0 AND 1000000),
  current_chapter  int NOT NULL DEFAULT 1 CHECK (current_chapter BETWEEN 1 AND 4),
  current_zone     text NOT NULL DEFAULT 'village' CHECK (current_zone IN ('village', 'mosswood', 'swamp', 'ruins')),
  save_state       jsonb NOT NULL DEFAULT jsonb_build_object(
    'schema_version', 1,
    'hero_class', NULL,
    'hero_level', 1,
    'hero_xp', 0,
    'skill_points', 0,
    'gold', 150,
    'gems', 0,
    'chapter', 1,
    'zone', 'village',
    'unlocked_zones', jsonb_build_array('village'),
    'quest', jsonb_build_object('chapter', 1, 'kills', 0, 'boss_defeated', false),
    'equipment', jsonb_build_object('weapon', jsonb_build_object('code', 'training-weapon', 'enhance', 0, 'rune', NULL)),
    'inventory', jsonb_build_object('moss', 0, 'wood', 0, 'slime_core', 0, 'swamp_ore', 0, 'ancient_shard', 0),
    'runes', '[]'::jsonb,
    'bosses', '{}'::jsonb,
    'play_seconds', 0
  ),
  state_version    int NOT NULL DEFAULT 1 CHECK (state_version > 0),
  last_save_key    text,
  last_played_at   timestamptz NOT NULL DEFAULT now(),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.pixel_forest_economy_ledger (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id       uuid NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  currency         text NOT NULL CHECK (currency IN ('gold', 'gems')),
  amount           int NOT NULL CHECK (amount <> 0),
  balance_after    int NOT NULL CHECK (balance_after >= 0),
  reason           text NOT NULL CHECK (reason IN ('loot', 'quest', 'boss', 'craft', 'enhance', 'rune', 'migration', 'save_sync')),
  idempotency_key  text NOT NULL,
  metadata         jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, idempotency_key, currency)
);

CREATE INDEX IF NOT EXISTS idx_pixel_forest_ledger_student_time
  ON public.pixel_forest_economy_ledger (student_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.pixel_forest_balance_events (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id    uuid NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  event_type    text NOT NULL CHECK (event_type IN (
    'session_start', 'session_end', 'class_selected', 'zone_enter', 'monster_kill',
    'player_death', 'boss_start', 'boss_clear', 'chapter_complete', 'item_craft',
    'weapon_enhance', 'rune_equip', 'damage_dealt', 'damage_taken'
  )),
  hero_class    text CHECK (hero_class IS NULL OR hero_class IN ('swordsman', 'ranger', 'mage')),
  hero_level    int CHECK (hero_level IS NULL OR hero_level BETWEEN 1 AND 50),
  chapter       int CHECK (chapter IS NULL OR chapter BETWEEN 1 AND 4),
  zone          text CHECK (zone IS NULL OR zone IN ('village', 'mosswood', 'swamp', 'ruins')),
  value         numeric,
  metadata      jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pixel_forest_events_type_time
  ON public.pixel_forest_balance_events (event_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_pixel_forest_events_class_zone
  ON public.pixel_forest_balance_events (hero_class, zone, created_at DESC);

